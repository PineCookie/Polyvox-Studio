def rewrite(text: str) -> str:
    names = "|".join(TOP)
    text = re.sub(r"^(\s*)from GPT_SoVITS\.", r"\1from ", text, flags=re.M)
    text = re.sub(rf"^(\s*)from ({names})(\.[\w.]+)? import ", rf"\1from {PKG}.\2\3 import ", text, flags=re.M)
    text = re.sub(rf"^(\s*)import ({names})(\.[\w.]+)?( as \w+)?$", rf"\1import {PKG}.\2\3\4", text, flags=re.M)
    return text


