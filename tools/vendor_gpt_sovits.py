def fetch(commit: str, into: Path) -> Path:
    """A shallow clone of ``commit`` (blobs of other commits not downloaded)."""
    run = lambda *cmd: subprocess.run(["git", "-C", str(into), *cmd], check=True)  # noqa: E731
    into.mkdir(parents=True)
    run("init", "-q")
    run("remote", "add", "origin", UPSTREAM)
    run("fetch", "-q", "--depth", "1", "origin", commit)
    run("checkout", "-q", "FETCH_HEAD")
    return into


def commit_of(checkout: Path) -> str:
    out = subprocess.run(["git", "-C", str(checkout), "rev-parse", "HEAD"], capture_output=True, text=True)
    return out.stdout.strip() or "?"


